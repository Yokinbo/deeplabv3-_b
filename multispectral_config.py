"""
DeepLabV3+ 多光谱任务统一配置。

这个文件的作用：
1. 把“当前训练/推理到底使用哪些波段”集中放在一个地方。
2. 自动根据所选波段数量得到模型输入通道数 in_channels。
3. 让 train.py、deeplab.py、predict.py、mIoU 评估脚本后续都读取同一份配置，
   避免训练用 6 通道、推理却还按 3 通道构建模型这类错误。

使用方法：
- 想训练普通真彩色 RGB：把 band_mode 改成 "rgb"
- 想训练 4 波段：把 band_mode 改成 "4band"
- 想训练 6 波段：把 band_mode 改成 "6band"

注意：
- 这里的波段编号使用 rasterio 的习惯，从 1 开始，而不是 Python 的 0 开始。
- 当前假设你的 6 波段 tif 内部顺序固定为：
  [1, 2, 3, 4, 5, 6] = [B2, B3, B4, B8, B11, B12]
"""

# ---------------------------------------------------------------------
# 训练好的权重路径
# ---------------------------------------------------------------------
# 后续 deeplab.py / predict.py / 多光谱get_miou.py 会默认从这里读取权重。
# 先按 UNet_b 当前习惯放到 logs/6band 下，等你训练出 DeepLab 权重后，
# 可以把文件名改成实际的 best_epoch_weights.pth。
trained_model_path = "logs/6band/best_epoch_weights.pth"

# ---------------------------------------------------------------------
# 波段模式
# ---------------------------------------------------------------------
# 可选值：
# "rgb"   -> 使用真彩色三波段：[B4, B3, B2]
# "4band" -> 使用蓝、绿、红、近红外：[B2, B3, B4, B8]
# "6band" -> 使用蓝、绿、红、近红外、短波红外1、短波红外2：
#             [B2, B3, B4, B8, B11, B12]
#
# 当前默认和 E:/UNet/UNet_b 的 myimprove 分支保持一致：6band。
band_mode = "6band"

# ---------------------------------------------------------------------
# 影像文件后缀
# ---------------------------------------------------------------------
# 原始 DeepLab 代码固定读取 .jpg。
# 多光谱 Sentinel-2 patch 通常是 .tif，因此这里统一改成可配置。
image_ext = ".tif"


# ---------------------------------------------------------------------
# 波段编号映射
# ---------------------------------------------------------------------
# 你的 tif 内部波段顺序假设为：
#   1 -> B2
#   2 -> B3
#   3 -> B4
#   4 -> B8
#   5 -> B11
#   6 -> B12
#
# 因此真彩色 RGB 不是 [1,2,3]，而是 [3,2,1]，
# 对应 [B4, B3, B2]。
band_options = {
    "rgb": [3, 2, 1],
    "4band": [1, 2, 3, 4],
    "6band": [1, 2, 3, 4, 5, 6],
}

if band_mode not in band_options:
    raise ValueError(
        f"未知的 band_mode={band_mode!r}，可选值为：{list(band_options.keys())}"
    )

# selected_bands 是训练/验证/推理实际读取的波段。
selected_bands = band_options[band_mode]

# in_channels 是模型第一层卷积需要的输入通道数。
# 后续 DeepLab 构建时必须使用这个值，否则 6 波段输入会和 3 通道模型不匹配。
in_channels = len(selected_bands)


# ---------------------------------------------------------------------
# 可视化波段
# ---------------------------------------------------------------------
# 多光谱推理时，模型可以吃 4/6 个通道，但结果叠加显示仍然需要一张 RGB 预览图。
# 这里固定使用真彩色 [B4, B3, B2] 做可视化。
vis_bands = [3, 2, 1]


# ---------------------------------------------------------------------
# 多光谱标准化配置
# ---------------------------------------------------------------------
# 训练和推理必须使用同一套预处理，否则模型看到的数据分布会前后不一致。
#
# 预处理顺序设计为：
# 1. reflectance_scale：
#    Sentinel-2 SR 常见导出值是 uint16 反射率 * 10000，
#    因此先除以 10000，把数值恢复到大致 0~1 的物理尺度。
#
# 2. enable_clip：
#    可选的逐波段裁剪。用于压制异常亮/暗像元、残云、边缘噪声等。
#
# 3. enable_mean_std：
#    可选的逐波段 mean/std 标准化。论文对比实验里建议使用，
#    但 mean/std 应该只从训练集统计，避免把验证/测试集信息泄漏进去。
#
# 下面的数值沿用 UNet_b/myimprove 当前配置，方便两个模型做同款实验对比。
normalization_configs = {
    "rgb": {
        # 对应 selected_bands = [3, 2, 1] = [B4, B3, B2]
        "reflectance_scale": 10000.0,
        "enable_clip": True,
        "clip_min": [0.029400, 0.044100, 0.024300],
        "clip_max": [0.286500, 0.228700, 0.207400],
        "enable_mean_std": True,
        "mean": [0.130562, 0.108342, 0.076092],
        "std": [0.053213, 0.038353, 0.034616],
    },
    "4band": {
        # 对应 selected_bands = [1, 2, 3, 4] = [B2, B3, B4, B8]
        "reflectance_scale": 10000.0,
        "enable_clip": True,
        "clip_min": [0.024300, 0.044100, 0.029400, 0.121600],
        "clip_max": [0.207400, 0.228700, 0.286500, 0.447600],
        "enable_mean_std": True,
        "mean": [0.076092, 0.108342, 0.130562, 0.243092],
        "std": [0.034616, 0.038353, 0.053213, 0.058950],
    },
    "6band": {
        # 对应 selected_bands = [1, 2, 3, 4, 5, 6]
        # 即 [B2, B3, B4, B8, B11, B12]
        "reflectance_scale": 10000.0,
        "enable_clip": True,
        "clip_min": [0.024300, 0.044100, 0.029400, 0.121600, 0.142000, 0.084200],
        "clip_max": [0.207400, 0.228700, 0.286500, 0.447600, 0.429700, 0.402300],
        "enable_mean_std": True,
        "mean": [0.076092, 0.108342, 0.130562, 0.243092, 0.284875, 0.234912],
        "std": [0.034616, 0.038353, 0.053213, 0.058950, 0.059411, 0.065606],
    },
}

# 当前模式实际使用的标准化参数。
# 后续 utils/utils.py 的 preprocess_input 会读取它。
normalization_config = normalization_configs[band_mode]
